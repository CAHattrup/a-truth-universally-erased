"""Convert Project Gutenberg plain-text Austen novels into texts/<key>.js.

Usage: python3 tools/build_texts.py <folder with Gutenberg .txt files>
Each output file defines one novel as a list of chapters, each a list of paragraphs.
"""
import json, re, sys, os

NOVELS = [
    ("pride", "1342.txt", "Pride and Prejudice", 1813),
    ("sense", "161.txt", "Sense and Sensibility", 1811),
    ("mansfield", "141.txt", "Mansfield Park", 1814),
    ("emma", "158.txt", "Emma", 1815),
    ("northanger", "121.txt", "Northanger Abbey", 1817),
    ("persuasion", "105.txt", "Persuasion", 1817),
]

CHAPTER = re.compile(r"^\s*chapter\s+([ivxlc\d]+)\.?\s*$", re.I)
VOLUME = re.compile(r"^\s*volume\s+([ivx\d]+)\.?\s*$", re.I)
SKIP = re.compile(r"^(the end|finis)\.?$", re.I)

def clean(par):
    par = " ".join(line.strip() for line in par.splitlines())
    par = par.replace("_", "")
    par = re.sub(r"\s*--\s*", "—", par)
    return re.sub(r"\s+", " ", par).strip()

def convert(path):
    raw = open(path, encoding="utf-8", errors="replace").read().replace("\r\n", "\n")
    start = re.search(r"\*\*\* ?START OF.*?\*\*\*", raw).end()
    end_m = re.search(r"(\*\*\* ?END OF|End of the Project Gutenberg|End of Project Gutenberg)", raw)
    body = raw[start:end_m.start()]
    chapters, volume, current = [], None, None
    for block in re.split(r"\n\s*\n", body):
        text = block.strip()
        if not text:
            continue
        if VOLUME.match(text):
            volume = VOLUME.match(text).group(1).upper()
            continue
        if CHAPTER.match(text):
            num = CHAPTER.match(text).group(1).upper()
            label = (f"Volume {volume}, " if volume else "") + f"Chapter {num}"
            current = {"label": label, "paras": []}
            chapters.append(current)
            continue
        if current is None or SKIP.match(text):
            continue
        current["paras"].append(clean(text))
    return chapters

src = sys.argv[1]
os.makedirs("texts", exist_ok=True)
for key, fname, title, year in NOVELS:
    chapters = convert(os.path.join(src, fname))
    words = sum(len(p.split()) for c in chapters for p in c["paras"])
    data = {"key": key, "title": title, "year": year, "chapters": chapters}
    with open(f"texts/{key}.js", "w", encoding="utf-8") as f:
        f.write("// " + title + " by Jane Austen (" + str(year) + "). Public domain.\n")
        f.write("// Source: Project Gutenberg. Generated by tools/build_texts.py.\n")
        f.write("window.AUSTEN_NOVELS = window.AUSTEN_NOVELS || {};\n")
        f.write("window.AUSTEN_NOVELS[" + json.dumps(key) + "] = " + json.dumps(data, ensure_ascii=False) + ";\n")
    print(f"{title}: {len(chapters)} chapters, {words} words, first: {chapters[0]['label']}, last: {chapters[-1]['label']}")
